"""
Три раздела приложения: названия и короткие описания для интерфейса.

Вынесено отдельно от app.py, чтобы текст было удобно править в одном месте
и проверять тестами: у каждого раздела обязано быть описание из трёх пунктов.
"""
from html import escape

MODE_REGISTRY = "Тест из реестра"
MODE_FILE = "Тест из файла"
MODE_LECTURE = "Тест из лекции"

MODES = [MODE_REGISTRY, MODE_FILE, MODE_LECTURE]

# Описание раздела: список пунктов (текст, выделить жирным).
MODE_POINTS: dict[str, list[tuple[str, bool]]] = {
    MODE_REGISTRY: [
        ("Берём файл преподавателя из базы данных в Moodle", False),
        ("Готовим тест", False),
        ("Отправляем результат обратно: в базу данных и в банк вопросов курса", True),
    ],
    MODE_FILE: [
        ("Загружаем файл с вопросами вручную", False),
        ("Готовим тест", False),
        ("Сами выбираем курс Moodle, в который отправить тест", True),
    ],
    MODE_LECTURE: [
        ("ИИ придумывает новые вопросы по PDF лекции", False),
        ("Ответы выбирает ИИ, поэтому вопросы нужно проверить", False),
        ("Скачиваем готовый тест, не загружая в курс Moodle "
         "(для загрузки готового теста воспользуйтесь вторым режимом)", False),
    ],
}

# Переключатель в разделе «Тест из файла»: слева режим выключенного, справа включённого.
SWITCH_OFF_LABEL = "Режим одного верного ответа"
SWITCH_ON_LABEL = "Режим всех типов вопросов"
SWITCH_ON_HINT = (
    "Без лимита в 25 вопросов, включая эссе и соответствие. "
    "Готовый тест в этом режиме можно только скачать: в Moodle он не отправляется."
)

# Разделы, где вопросы берутся из готового файла преподавателя (до 25, с отчётом о пропущенном).
COURSE_MODES = (MODE_REGISTRY, MODE_FILE)


def render_mode_description_html(mode: str) -> str:
    """Описание выбранного раздела: список пунктов, ключевой пункт жирным (текст экранирован)."""
    if mode not in MODE_POINTS:
        raise ValueError(f"Неизвестный раздел: {mode!r}")
    items = "".join(
        f"<li>{'<strong>' if bold else ''}{escape(text)}{'</strong>' if bold else ''}</li>"
        for text, bold in MODE_POINTS[mode]
    )
    return f"<ul class='imes-mode-list'>{items}</ul>"
