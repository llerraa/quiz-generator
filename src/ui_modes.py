def render_mode_comparison_html(current_mode: str) -> str:
    """
    Таблица различий режимов в виде HTML; столбец выбранного режима подсвечен.

    Вся текстовая часть экранируется: таблица попадает в st.markdown с
    unsafe_allow_html, и текст не должен случайно стать разметкой.
    """
    if current_mode not in MODES:
        raise ValueError(f"Неизвестный режим: {current_mode!r}")
    current_index = MODES.index(current_mode)

    def cls(index: int) -> str:
        return " class='is-current'" if index == current_index else ""

    head = "".join(f"<th{cls(i)}>{escape(label)}</th>" for i, label in enumerate(MODES))
    body_rows = []
    for title, *cells in COMPARISON_ROWS:
        cells_html = "".join(f"<td{cls(i)}>{escape(text)}</td>" for i, text in enumerate(cells))
        body_rows.append(f"<tr><th class='rowhead'>{escape(title)}</th>{cells_html}</tr>")

    return (
        "<div class='imes-compare-wrap'><table class='imes-compare'>"
        f"<thead><tr><th class='rowhead'></th>{head}</tr></thead>"
        f"<tbody>{''.join(body_rows)}</tbody></table></div>"
    )